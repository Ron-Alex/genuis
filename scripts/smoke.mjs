import assert from "node:assert/strict";
const base = "http://localhost:3107";
const page = await fetch(base);
assert.equal(page.status, 200);
assert.match(await page.text(), /Genuis/);
console.log("PASS: application page responds");
const response = await fetch(`${base}/api/banking`);
const snapshot = await response.json();
assert.equal(response.status, 200, snapshot.error);
assert.ok(Array.isArray(snapshot.accounts));
assert.ok(Array.isArray(snapshot.purchases));
console.log(`PASS: banking snapshot (${snapshot.mode}, ${snapshot.engine})`);
const invalid = await fetch(`${base}/api/agent`, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ prompt: "x" }) });
assert.equal(invalid.status, 400);
const foreign = await fetch(`${base}/api/agent`, { method: "POST", headers: { Origin: "https://untrusted.example" }, body: "{}" });
assert.equal(foreign.status, 403);
console.log("PASS: invalid and cross-origin agent requests rejected");
const dashboard = { version: 0, theme: "light", largeText: false, widgets: [] };
if (snapshot.engine === "demo") {
  const result = await fetch(`${base}/api/agent`, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ prompt: "Generate a custom restaurant tracker for October", dashboard }) });
  assert.equal(result.status, 200);
  const lines = (await result.text()).trim().split("\n").map(JSON.parse);
  assert.ok(!lines.some(l => l.type === "error"), JSON.stringify(lines.filter(l => l.type === "error")));
  assert.ok(lines.some(l => l.type === "event" && l.event.stage === "builder"));
  const final = lines.find(l => l.type === "result");
  assert.ok(final);
  assert.equal(final.result.dashboard.widgets.length, 1);
  assert.equal(final.result.dashboard.widgets[0].kind, "custom");
  const compile = await fetch(`${base}/api/component`, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ code: final.result.dashboard.widgets[0].code }) });
  const bundle = await compile.json();
  assert.equal(compile.status, 200, bundle.error);
  assert.match(bundle.script, /genuis-widget-ready/);
  console.log("PASS: streamed orchestration -> generated component -> React bundle");
  const theme = await fetch(`${base}/api/agent`, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ prompt: "High contrast theme and larger text", dashboard }) });
  const themed = (await theme.text()).trim().split("\n").map(JSON.parse).find(l => l.type === "result");
  assert.equal(themed.result.dashboard.theme, "contrast"); assert.equal(themed.result.dashboard.largeText, true);
  console.log("PASS: theme workflow");
} else console.log("SKIP: demo orchestration checks; a live model is configured (no paid smoke calls made).");
const rejected = await fetch(`${base}/api/component`, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ code: "function GeneratedWidget(){fetch('https://bad.example');return null}" }) });
assert.equal(rejected.status, 422);
console.log("PASS: restricted generated component rejected");
